#!/usr/bin/env python3
"""build.py - the indexer. Python 3, standard library only.

Scans every .md file under the notes folder and writes viewer/graph-data.js:

    const GRAPH = {nodes: [...], links: [...]};

Each node: id (== its index in the nodes array), label (from the filename),
group (parent folder), path (relative to the notes folder), excerpt (~700 chars).
Two notes are linked when one mentions the other's title or they share a [[wikilink]].

server.py imports this module so a captured note is linked exactly the same way.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
VIEWER = os.path.join(ROOT, "viewer")
GRAPH_JS = os.path.join(VIEWER, "graph-data.js")
EXCERPT_CHARS = 700
WIKILINK = re.compile(r"\[\[([^\]|#]+)(?:[#|][^\]]*)?\]\]")


def load_config():
    with open(os.path.join(ROOT, "config.json"), encoding="utf-8") as f:
        return json.load(f)


def notes_dir(config=None):
    config = config or load_config()
    path = config.get("notes_dir", "notes")
    return path if os.path.isabs(path) else os.path.join(ROOT, path)


def make_excerpt(text):
    """Strip the leading H1 (the label already shows it) and trim to ~700 chars on a word."""
    body = re.sub(r"^\s*#\s+[^\n]*\n", "", text, count=1).strip()
    body = WIKILINK.sub(lambda m: m.group(1).strip(), body)   # [[Title]] reads as Title
    if len(body) <= EXCERPT_CHARS:
        return body
    cut = body[:EXCERPT_CHARS]
    return cut[: cut.rfind(" ")].rstrip(",;:") + " ..."


def read_note(path, base):
    with open(path, encoding="utf-8", errors="replace") as f:
        text = f.read()
    rel = os.path.relpath(path, base)
    parent = os.path.basename(os.path.dirname(path))
    group = parent if os.path.dirname(rel) else "notes"
    return {
        "label": os.path.splitext(os.path.basename(path))[0],
        "group": group,
        "path": rel.replace(os.sep, "/"),
        "excerpt": make_excerpt(text),
        "_text": text,
    }


def note_meta(node):
    """Facts used for linking: lowercased text and the set of wikilink targets."""
    text = node.get("_text") or node["excerpt"]
    return text.lower(), {w.strip().lower() for w in WIKILINK.findall(text)}


def should_link(a, b, meta_a, meta_b):
    text_a, wl_a = meta_a
    text_b, wl_b = meta_b
    la, lb = a["label"].lower(), b["label"].lower()
    if la in wl_b or lb in wl_a:          # explicit [[wikilink]] either way
        return True
    if len(wl_a & wl_b) >= 2:              # they share [[wikilinks]] (two or more targets in common)
        return True
    # one mentions the other's title in plain text (titles of 4+ chars, whole word)
    def mentions(text, label):
        return len(label) >= 4 and re.search(r"(?<!\w)" + re.escape(label) + r"(?!\w)", text)
    return bool(mentions(text_a, lb) or mentions(text_b, la))


def links_for(index, nodes, metas):
    """Links between nodes[index] and every earlier/later node. Used by build and by /remember."""
    out = []
    for j, other in enumerate(nodes):
        if j != index and should_link(nodes[index], other, metas[index], metas[j]):
            out.append({"source": min(index, j), "target": max(index, j)})
    return out


def build_graph(base):
    paths = []
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
        for name in sorted(filenames):
            if name.lower().endswith(".md"):
                paths.append(os.path.join(dirpath, name))
    nodes = [read_note(p, base) for p in paths]
    for i, n in enumerate(nodes):
        n["id"] = i                        # CRITICAL: id equals the index in the nodes array
    metas = [note_meta(n) for n in nodes]
    links, seen = [], set()
    for i in range(len(nodes)):
        for link in links_for(i, nodes, metas):
            key = (link["source"], link["target"])
            if key not in seen:
                seen.add(key)
                links.append(link)
    return nodes, links


def public(node):
    return {k: v for k, v in node.items() if not k.startswith("_")}


def write_graph_js(nodes, links, path=GRAPH_JS):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    data = {"nodes": [public(n) for n in nodes], "links": links}
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write("// Generated by build.py. Do not edit by hand.\n")
        f.write("const GRAPH = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
    os.replace(tmp, path)                  # atomic: the browser never reads half a file


def main():
    base = notes_dir()
    if not os.path.isdir(base):
        sys.exit(f"notes folder not found: {base}")
    nodes, links = build_graph(base)
    write_graph_js(nodes, links)
    print(f"indexed {len(nodes)} notes, {len(links)} links -> {os.path.relpath(GRAPH_JS, ROOT)}")


if __name__ == "__main__":
    main()
